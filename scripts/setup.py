def _assignments(text: str) -> Iterator[tuple[str, str]]:
    """Yield ``(key, raw value)`` for every assignment line, skipping blanks and comments."""
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, raw_value = stripped.split("=", 1)
        if key.strip():
            yield key.strip(), raw_value.strip()


def _unquote_env_value(raw: str) -> str:
    if len(raw) >= 2 and raw.startswith('"') and raw.endswith('"'):
        return raw[1:-1]
    return raw


def _quote_env_value(value: str) -> str:
    return f'"{value}"' if any(character in value for character in " #") else value


def parse_env_file(text: str) -> dict[str, str]:
    """Parse the ``KEY=value`` form used by the project's env files."""
    return {key: _unquote_env_value(raw) for key, raw in _assignments(text)}


def render_env_file(pairs: Mapping[str, str], preserved: Sequence[str] = ()) -> str:
    """Render the managed values, then the assignment lines setup does not manage."""
    lines = [
        "# Generated by scripts/setup.py. Existing comments are kept in .env.bak.",
        "# Private deployment values belong in this file, not in version control.",
        "",
        *(f"{key}={_quote_env_value(pairs[key])}" for key in MANAGED_KEYS if key in pairs),
        *preserved,
    ]
    return "\n".join(lines) + "\n"


def validate_env_value(value: str) -> str | None:
    """Reject the characters whose meaning differs between the readers of an env file.

    The backend reads ``.env`` with Node's ``util.parseEnv`` and Docker Compose reads it as an
    ``env_file``. The two disagree about backslash and quote escapes inside a value, so setup writes
    only the subset they read alike: a value may be wrapped in double quotes but never escape one.
    """
    if '"' in value or "\\" in value:
        return "Enter a value without double quotes or backslashes."
    return None


def _url_error(value: str, requirement: str, *, allow_path: bool) -> str | None:
    try:
        parsed = urlparse(value)
        _ = parsed.port
    except ValueError:
        return requirement
    if (
        value != value.strip()
        or any(character.isspace() for character in value)
        or parsed.scheme not in {"http", "https"}
        or not parsed.netloc
        or parsed.username is not None
        or parsed.password is not None
        or (not allow_path and parsed.path not in {"", "/"})
        or parsed.params
        or parsed.query
        or parsed.fragment
    ):
        return requirement
    return None


def validate_origin(value: str, _mode: str = "") -> str | None:
    requirement = "Enter a bare absolute http(s) origin with no path, query, or fragment."
    return _url_error(value, requirement, allow_path=False)


def validate_http_url(value: str, _mode: str = "") -> str | None:
    requirement = "Enter an absolute http(s) URL without credentials, a query, or a fragment."
    return _url_error(value, requirement, allow_path=True)


def validate_auth_secret(value: str) -> str | None:
    if len(value) < 32 or value == DEV_AUTH_SECRET:
        return "AUTH_SECRET must be at least 32 characters and must not use the development secret."
    return None


def validate_admin_email(value: str, _mode: str = "") -> str | None:
    if (
        value.lower() == DEV_ADMIN_EMAIL
        or "@" not in value
        or any(character.isspace() for character in value)
    ):
        return "Enter a real administrator email address."
    return None


def validate_admin_password(value: str, _mode: str = "") -> str | None:
    if not value or value == DEV_ADMIN_PASSWORD:
        return "Choose an administrator password other than the development password."
    return None


def validate_data_dir(value: str, mode: str) -> str | None:
    if not value:
        return "The data directory is required."
    if mode == "docker" and not value.startswith("/"):
        return "Docker deployment needs an absolute data directory shared by the host and container."
    return None


def validate_oauth(client_id: str, client_secret: str) -> str | None:
    if bool(client_id) != bool(client_secret):
        return "GitHub OAuth needs both a client ID and a client secret."
    return None


def validate_port(value: str, _mode: str = "") -> str | None:
    if not value.isdigit() or not 1 <= int(value) <= 65535:
        return "The site port must be an integer from 1 through 65535."
    return None


def docker_mode_error(platform: str) -> str | None:
    if platform in {"win32", "darwin"}:
        return (
            "Docker deployment needs a Linux Docker daemon because the data directory must have the same "
            "path on the host and in the app container. Use host mode, or run under WSL2."
        )
    return None


PromptDefault = Callable[[str], str]
PromptValidator = Callable[[str, str], str | None]


def _empty_default(_mode: str) -> str:
    return ""


def _fixed_default(value: str) -> PromptDefault:
    return lambda _mode: value


def _password_default(_mode: str) -> str:
    return secrets.token_urlsafe(12)


def _data_dir_default(mode: str) -> str:
    return "/srv/game-sandbox/data" if mode == "docker" else "backend/data"



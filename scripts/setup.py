MANAGED_KEYS = tuple(ENV_FIELDS)
MANAGED_KEY_SET = frozenset(MANAGED_KEYS)
REQUIRED_ENV_KEYS = frozenset(key for key, field in ENV_FIELDS.items() if field.required)


